package main

import (
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func (m *manager) configPath() string { return filepath.Join(m.root, "etc", "omd", "packages.conf") }

func (m *manager) settingsPath() string { return filepath.Join(m.root, "etc", "omd", "settings.conf") }

func (m *manager) loadConfig() (map[string]bool, error) {
	data, err := os.ReadFile(m.configPath())
	if err != nil {
		return nil, err
	}
	selected := make(map[string]bool)
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		id, state, ok := strings.Cut(line, "=")
		id, state = strings.TrimSpace(id), strings.TrimSpace(state)
		hasID := func(p Package) bool { return p.ID == id }
		known := slices.ContainsFunc(m.packages, hasID)
		// Packages for another OS, such as Homebrew on Linux, are ignored.
		if !known && slices.ContainsFunc(registry(), hasID) {
			continue
		}
		if !ok || !known || (state != "enabled" && state != "disabled") {
			return nil, fmt.Errorf("%s:%d: invalid package selection %q", m.configPath(), i+1, line)
		}
		selected[id] = state == "enabled"
	}
	return selected, nil
}

func atomicWrite(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".omd-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	_, writeErr := io.WriteString(f, content)
	closeErr := f.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func (m *manager) saveConfig(selected map[string]bool) error {
	var b strings.Builder
	b.WriteString("# Generated by omd\n")
	for _, p := range m.packages {
		state := "disabled"
		if selected[p.ID] {
			state = "enabled"
		}
		fmt.Fprintf(&b, "%s=%s\n", p.ID, state)
	}
	return atomicWrite(m.configPath(), b.String())
}

func (m *manager) generateEnv(selected map[string]bool) error {
	var b strings.Builder
	b.WriteString("# Generated by omd — do not edit\n# Regenerate with: omd env\n\ntypeset -U path\n")
	// Snippets are ordered by EnvOrder (stable within equal values).
	var ordered []Package
	for _, p := range m.packages {
		if selected[p.ID] && p.Env != "" {
			ordered = append(ordered, p)
		}
	}
	slices.SortStableFunc(ordered, func(a, b Package) int { return a.EnvOrder - b.EnvOrder })
	present, checkErr := m.probeAll(ordered)
	for _, p := range ordered {
		if present[p.ID] {
			fmt.Fprintf(&b, "\n# %s\n%s", p.ID, p.Env)
		}
	}
	// A package whose check timed out is left out and reported, not silently dropped.
	return errors.Join(atomicWrite(filepath.Join(m.root, "etc", "omd", "env.sh"), b.String()), checkErr)
}

// defaultSelection preselects the packages marked Default on this platform.
func (m *manager) defaultSelection() map[string]bool {
	selected := make(map[string]bool)
	for _, p := range m.packages {
		selected[p.ID] = p.Default
	}
	return selected
}
